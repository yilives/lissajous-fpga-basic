        end
    end

    // Synchronise the accepted UART2 command into the DDS clock domain. The
    // command fields are held until the next command, so two-stage sampling is
    // sufficient; pc_commit_sync changes only after they are stable.
    always @(negedge dac_sample_clk or negedge pll_locked) begin
        if (!pll_locked) begin
            pc_ctrl_live_meta    <= 1'b0;
            pc_ctrl_live_sync    <= 1'b0;
            pc_waveform_meta     <= 2'd0;
            pc_waveform_sync     <= 2'd0;
            pc_ramp_p_meta       <= 8'd1;
            pc_ramp_p_sync       <= 8'd1;
            pc_phase_step_meta   <= 32'd0;
            pc_phase_step_sync   <= 32'd0;
            pc_phase_meta        <= 32'd0;
            pc_phase_sync        <= 32'd0;
            pc_phase_apply_meta  <= 1'b0;
            pc_phase_apply_sync  <= 1'b0;
            pc_amplitude_meta    <= 10'd0;
            pc_amplitude_sync    <= 10'd0;
            pc_commit_meta       <= 1'b0;
            pc_commit_sync       <= 1'b0;
        end else begin
            pc_ctrl_live_meta    <= pc_ctrl_live;
            pc_ctrl_live_sync    <= pc_ctrl_live_meta;
            pc_waveform_meta     <= pc_ctrl_waveform;
            pc_waveform_sync     <= pc_waveform_meta;
            pc_ramp_p_meta       <= pc_ctrl_ramp_p;
            pc_ramp_p_sync       <= pc_ramp_p_meta;
            pc_phase_step_meta   <= pc_ctrl_phase_step;
            pc_phase_step_sync   <= pc_phase_step_meta;
            pc_phase_meta        <= pc_ctrl_phase;
            pc_phase_sync        <= pc_phase_meta;
            pc_phase_apply_meta  <= pc_ctrl_phase_apply;
            pc_phase_apply_sync  <= pc_phase_apply_meta;
            pc_amplitude_meta    <= pc_ctrl_amplitude;
            pc_amplitude_sync    <= pc_amplitude_meta;
            pc_commit_meta       <= pc_ctrl_commit_toggle;
            pc_commit_sync       <= pc_commit_meta;
        end
    end

    // DAC DDS is fully in the 25 MHz dac_sample_clk domain. Data is registered on the
    // falling edge and has 5 ns to settle before AD9764 samples it.
    always @(negedge dac_sample_clk or negedge pll_locked) begin
        if (!pll_locked) begin
            nco_phase_dac       <= 32'd0;
            nco_step_reg        <= DEFAULT_DAC_PHASE_STEP;
            nco_increment_reg   <= DEFAULT_DAC_PHASE_STEP;
            requested_phase_anchor_reg <= DEFAULT_PHASE_ANCHOR;
            phase_correction_reg <= 32'sd0;
            phase_correction_apply_reg <= 32'sd0;
            phase_error_sum      <= 36'sd0;
            phase_error_count    <= 3'd0;
            phase_rate_correction <= 32'sd0;
            pc_commit_seen      <= 1'b0;
            dac_update_count    <= DDS_UPDATE_DIV_MINUS1;
            sine_base_stage0    <= 12'd0;
            sine_next_stage0    <= 12'd0;
            sine_fraction_stage0 <= 8'd0;
            sine_descending_stage0 <= 1'b0;
            sine_negative_stage0 <= 1'b0;
            sine_base_stage1    <= 12'd0;
            sine_delta_stage1   <= 12'd0;
            sine_fraction_stage1 <= 8'd0;
            sine_descending_stage1 <= 1'b0;
            sine_negative_stage1 <= 1'b0;
            sine_interp_product_stage2 <= 20'd0;
            sine_base_stage2    <= 12'd0;
            sine_descending_stage2 <= 1'b0;
            sine_negative_stage2 <= 1'b0;
            sine_code_reg       <= 13'sd0;
            phase_step_dac_meta <= DEFAULT_DAC_PHASE_STEP;
            phase_step_dac_sync <= DEFAULT_DAC_PHASE_STEP;
            phase_anchor_meta   <= DEFAULT_PHASE_ANCHOR;
            phase_anchor_sync   <= DEFAULT_PHASE_ANCHOR;
            input_path_phase_meta <= DEFAULT_PATH_PHASE_ADVANCE;
            input_path_phase_sync <= DEFAULT_PATH_PHASE_ADVANCE;
            phase_cross_fraction_meta <= 8'd128;
            phase_cross_fraction_sync <= 8'd128;
            input_pp_meta       <= 10'd0;
            input_pp_dac        <= 10'd0;
            adc_data_meta       <= 10'd512;
            adc_data_dac        <= 10'd512;
            anchor_toggle_meta  <= 1'b0;
            anchor_toggle_sync  <= 1'b0;
            anchor_toggle_seen  <= 1'b0;
            anchor_phase_snap_meta <= 32'd0;
            anchor_phase_snap_sync <= 32'd0;
            mode_select_meta    <= MODE_LINE;
            mode_select_dac     <= MODE_LINE;
            requested_pp_code_reg <= 10'd0;
            amplitude_gain_product_reg <= 21'd0;
            output_pp_code_reg <= 10'd0;
            dac_product_reg     <= 24'sd0;
            dac_data_reg        <= 14'h2000;
            dds_rom_fraction_reg <= 22'd0;
            reference_nco_phase <= 32'd0;
            bit_walk_count      <= 14'd0;
            bit_walk_index      <= 4'd0;
        end else begin
            dds_rom_fraction_reg <= dds_wave_phase_dac[21:0];
            // Clock-domain crossing registers run at the DAC clock; external
            // ADC estimates are transferred only through synchronizer stages.
            phase_step_dac_meta <= phase_step_dac_adc;
            phase_step_dac_sync <= phase_step_dac_meta;
            phase_anchor_meta   <= phase_anchor_adc;
            phase_anchor_sync   <= phase_anchor_meta;
            input_path_phase_meta <= input_path_phase_adc;
            input_path_phase_sync <= input_path_phase_meta;
            phase_cross_fraction_meta <= phase_cross_fraction_adc;
            phase_cross_fraction_sync <= phase_cross_fraction_meta;
            input_pp_meta       <= input_pp_code;
            input_pp_dac        <= input_pp_meta;
            adc_data_meta       <= adc_raw_sample;
            adc_data_dac        <= adc_data_meta;
            anchor_toggle_meta  <= anchor_toggle_adc;
            anchor_toggle_sync  <= anchor_toggle_meta;
            anchor_phase_snap_meta <= anchor_phase_snap_adc;
            anchor_phase_snap_sync <= anchor_phase_snap_meta;
            mode_select_meta    <= mode_select_adc;
            mode_select_dac     <= mode_select_meta;

            if (dac_data_update_tick) begin
                dac_update_count <= 2'd0;
                sine_base_stage0 <= sine_base_from_nco;
                sine_next_stage0 <= sine_next_from_nco;
                sine_fraction_stage0 <= nco_phase_dac[25:18];
                sine_descending_stage0 <= sine_descending_from_nco;
                sine_negative_stage0 <= sine_negative_from_nco;
                sine_base_stage1 <= sine_base_stage0;
                sine_delta_stage1 <= sine_delta_stage0;
                sine_fraction_stage1 <= sine_fraction_stage0;
                sine_descending_stage1 <= sine_descending_stage0;
                sine_negative_stage1 <= sine_negative_stage0;
                sine_interp_product_stage2 <= sine_delta_stage1 * sine_fraction_stage1;
                sine_base_stage2 <= sine_base_stage1;
                sine_descending_stage2 <= sine_descending_stage1;
                sine_negative_stage2 <= sine_negative_stage1;
                sine_code_reg <= dds_sine_code_from_rom;

                // Data changes on every 25 MHz DAC update and remains
                // registered on the falling edge before the DAC rising edge.
                if (DDS_FIXED_100K_DIAGNOSTIC) begin
                    // Pure DAC-path test: one exact 100 kHz NCO increment,
                    // no ADC-derived frequency or asynchronous phase kick.
                    nco_step_reg <= FIXED_100K_DAC_PHASE_STEP;
                    nco_increment_reg <= FIXED_100K_DAC_PHASE_STEP;
                    requested_phase_anchor_reg <= 32'd0;
                    phase_correction_reg <= 32'sd0;
                    phase_correction_apply_reg <= 32'sd0;
            phase_error_sum      <= 36'sd0;
            phase_error_count    <= 3'd0;
            phase_rate_correction <= 32'sd0;
                    anchor_toggle_seen <= anchor_toggle_sync;
                    nco_phase_dac <= nco_phase_dac + FIXED_100K_DAC_PHASE_STEP;
                end else if (pc_ctrl_live_sync) begin
                    // PC visual loop owns frequency, phase and amplitude in
                    // this mode. Refresh frames need not reset phase; only a
                    // command with APPLY_PHASE explicitly restarts the NCO.
                    nco_step_reg <= pc_phase_step_sync;
                    nco_increment_reg <= pc_phase_step_sync;
                    requested_phase_anchor_reg <= pc_phase_sync;
                    phase_correction_reg <= 32'sd0;
                    phase_correction_apply_reg <= 32'sd0;
                    phase_error_sum <= 36'sd0;
                    phase_error_count <= 3'd0;
                    phase_rate_correction <= 32'sd0;
                    anchor_toggle_seen <= anchor_toggle_sync;
                    if (pc_commit_sync != pc_commit_seen) begin
                        pc_commit_seen <= pc_commit_sync;
                        if (pc_phase_apply_sync)
                            nco_phase_dac <= pc_phase_sync;
                        else
                            nco_phase_dac <= nco_phase_dac + pc_phase_step_sync;
                    end else begin
                        nco_phase_dac <= nco_phase_dac + pc_phase_step_sync;
                    end
                end else begin
                    pc_commit_seen <= pc_commit_sync;
                    // [AI Mod: pure zero-crossing follow mode 2026-08-01]
                    // Frequency = period-tracker word (proven estimator).
                    // Phase = zero-crossing anchor: each ADC zero crossing
                    // pulls the NCO phase 1/16 toward 0.  No I/Q terms.  The
                    // 90-degree / 2f offsets live in local_wave_phase_dac.
                    nco_step_reg <= phase_step_dac_sync;
                    nco_increment_reg <= phase_step_dac_sync;
                    requested_phase_anchor_reg <= (mode_select_dac == MODE_CIRCLE_MATCH) ?
                        (32'h40000000 + QUADRATURE_PHASE_TRIM + dac_path_phase_advance) :
                        (mode_select_dac == MODE_LINE) ?
                        dac_path_phase_advance :
                        (double_dac_path_phase_advance + double_extra_phase_advance_twice);
                    phase_correction_reg <= 32'sd0;
                    phase_correction_apply_reg <= 32'sd0;
                    phase_rate_correction <= 32'sd0;
                    if (anchor_toggle_sync != anchor_toggle_seen) begin
                        anchor_toggle_seen <= anchor_toggle_sync;
                        // [AI Mod: pull the crossing-time phase (snapshot)
                        // toward 0 by 1/16; the snapshot + signed-error fix
                        // removes the detection-delay offset (~97 deg at
                        // 100 kHz) and the 0/2pi boundary flips]
                        nco_phase_dac <= nco_phase_dac +
                            (anchor_snap_err >>> 4);
                    end else begin
                        nco_phase_dac <= nco_phase_dac + phase_step_dac_sync;
                    end
                end

                // Register the mode/input selection before the calibrated
                // gain multiply.  This keeps mode-key routing out of the
                // 125 MHz amplitude path.
                requested_pp_code_reg <= DDS_FIXED_100K_DIAGNOSTIC ?
                    FIXED_100K_PP_CODE : selected_pp_code;
                amplitude_gain_product_reg <= amplitude_gain_product;
                output_pp_code_reg <= output_pp_code;
                dac_product_reg    <= selected_wave_code * $signed({1'b0, output_pp_code_reg});
                reference_nco_phase <= reference_nco_phase + FIXED_100K_DAC_PHASE_STEP;
                if (REFERENCE_ROM_100K_DIAGNOSTIC) begin
                    dac_data_reg <= reference_rom_dac_code;
                end else if (DAC_BIT_WALK_DIAGNOSTIC) begin
                    if (bit_walk_count == BIT_WALK_HOLD_TICKS - 1) begin
                        bit_walk_count <= 14'd0;
                        if (bit_walk_index == 4'd13)
                            bit_walk_index <= 4'd0;
                        else
                            bit_walk_index <= bit_walk_index + 1'b1;
                    end else begin
                        bit_walk_count <= bit_walk_count + 1'b1;
                    end
                    dac_data_reg <= bit_walk_dac_code;
                end else if (ADC_RAW_DIAGNOSTIC) begin
                    dac_data_reg <= calibrated_raw_dac_code;
                end else begin
                    dac_data_reg <= generated_dac_code;
                end
            end else begin
                dac_update_count <= dac_update_count + 1'b1;
            end
        end
    end
    // =====================================================================
    // OLED SSD1306 Display (128x32, I2C, 2 lines x 16 chars)
    // =====================================================================
    // Build display text from current mode and amplitude
    wire [7:0] mode_digit = 8'h30 + {5'd0, mode_select_dac} + 8'd1; // MODE:1..7

    // Line 0: "MODE:X          " (padded with spaces)
    wire [127:0] oled_line0 = {
        8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20,
        8'h20, 8'h20, 8'h20, mode_digit, 8'h3A, 8'h45, 8'h44, 8'h4F
    }; // "MODE:X" + spaces (stored char0 first in low bits)

    // Line 1: "PP:XXXX         " (amplitude in hex)
    wire [7:0] pp_hex_hi = {6'd0, input_pp_dac[9:8]} + 8'd48; // 0-3, always digit
    wire [7:0] pp_hex_mh = (input_pp_dac[7:4] > 4'd9) ?
                           ({4'd0, input_pp_dac[7:4]} + 8'd55) :
                           ({4'd0, input_pp_dac[7:4]} + 8'd48);
    wire [7:0] pp_hex_ml = (input_pp_dac[3:0] > 4'd9) ?
                           ({4'd0, input_pp_dac[3:0]} + 8'd55) :
                           ({4'd0, input_pp_dac[3:0]} + 8'd48);
    wire [127:0] oled_line1 = {
        8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20, 8'h20,
        8'h20, 8'h20,
        pp_hex_ml, pp_hex_mh, pp_hex_hi, 8'h3A, 8'h50, 8'h50
    }; // "PP:XXX" + spaces

    // =====================================================================
    // Independent power-on reset for peripherals (does NOT depend on PLL)
    // Holds reset for ~84 ms after configuration, then releases.
    // =====================================================================
    // 50 MHz * 84 ms = 4,200,000, which requires 23 bits.
    reg [22:0] por_cnt;
    reg        por_done;

    // The board has no reset input wired to this design.  Make the intended
    // configuration power-up state explicit so the UART and OLED always see
    // a real reset pulse after every FPGA configuration.
    initial begin
        por_cnt  = 23'd0;
        por_done = 1'b0;
    end

    always @(posedge clk_50m) begin
        if (!por_done) begin
            if (por_cnt == 23'd4199999) // ~84 ms @ 50 MHz
                por_done <= 1'b1;
            else
                por_cnt <= por_cnt + 1'b1;
        end
    end
    wire por_rst_n = por_done;
    wire [3:0] oled_state_dbg;
    wire       oled_addr_3d_dbg, oled_addr_ack_dbg;
    wire [7:0] oled_nack_count_dbg;

    ssd1306_oled #(
        .CLK_FREQ(PLL_INPUT_CLK_HZ)
    ) u_oled (
        .clk     (clk_50m),
        .rst_n   (por_rst_n),
        .line0   (oled_line0),
        .line1   (oled_line1),
        .oled_scl(oled_scl),
        .oled_sda(oled_sda),
        .debug_state(oled_state_dbg),
        .debug_addr_3d(oled_addr_3d_dbg),
        .debug_addr_ack(oled_addr_ack_dbg),
        .debug_nack_count(oled_nack_count_dbg)
    );

    // =====================================================================
    // UART1 remains an independent diagnostic echo. UART2 is reserved for the
    // PC visual closed loop and never emits unframed status text.
    wire [7:0] uart1_rx_data, uart1_fifo_data;
    wire uart1_rx_valid, uart1_fifo_empty, uart1_fifo_full, uart1_tx_busy;
    wire uart1_echo_fire = !uart1_tx_busy && !uart1_fifo_empty;

    uart_byte_fifo u_uart1_fifo (
        .clk(clk_50m), .rst_n(por_rst_n), .wr_data(uart1_rx_data), .wr_en(uart1_rx_valid),
        .rd_en(uart1_echo_fire), .rd_data(uart1_fifo_data), .empty(uart1_fifo_empty), .full(uart1_fifo_full)
    );
    uart_tx #(.CLK_FREQ(PLL_INPUT_CLK_HZ), .BAUD(115200)) u_uart1_tx (
        .clk(clk_50m), .rst_n(por_rst_n),
        .tx_data(uart1_fifo_data), .tx_valid(uart1_echo_fire),
        .tx_busy(uart1_tx_busy), .uart_txd(uart1_txd)
    );
    uart_rx #(.CLK_FREQ(PLL_INPUT_CLK_HZ), .BAUD(115200)) u_uart1_rx (
        .clk(clk_50m), .rst_n(por_rst_n), .rx_data(uart1_rx_data), .rx_valid(uart1_rx_valid), .uart_rxd(uart1_rxd)
    );

    // S3 is a persistent visual/normal selector, independent of S4's output
    // shape selection. Power-up is normal mode; each debounced press toggles.
    always @(posedge clk_50m or negedge por_rst_n) begin
        if (!por_rst_n) begin
            vision_key_meta       <= 1'b1;
            vision_key_sync       <= 1'b1;
            vision_key_stable     <= 1'b1;
            vision_key_count      <= 19'd0;
            visual_mode_enabled   <= 1'b0;
        end else begin
            vision_key_meta <= vision_key_n;
            vision_key_sync <= vision_key_meta;
            if (vision_key_sync == vision_key_stable) begin
                vision_key_count <= 19'd0;
            end else if (vision_key_count == VISION_KEY_DEBOUNCE_TICKS - 1) begin
                vision_key_count  <= 19'd0;
                vision_key_stable <= vision_key_sync;
                if (!vision_key_sync)
                    visual_mode_enabled <= ~visual_mode_enabled;
            end else begin
                vision_key_count <= vision_key_count + 1'b1;
            end
        end
    end
    wire        pc_ctrl_enabled;
    wire        pc_ctrl_live;
    wire [1:0]  pc_ctrl_waveform;
    wire [7:0]  pc_ctrl_ramp_p;
    wire [31:0] pc_ctrl_phase_step;
    wire [31:0] pc_ctrl_phase;
    wire        pc_ctrl_phase_apply;
    wire [9:0]  pc_ctrl_amplitude;
    wire        pc_ctrl_commit_toggle;

    uart2_dds_control #(
        .CLK_FREQ(PLL_INPUT_CLK_HZ),
        .BAUD(115200)
    ) u_uart2_dds_control (
        .clk(clk_50m),
        .rst_n(por_rst_n),
        .visual_mode_enabled(visual_mode_enabled),
        .uart_rxd(uart2_rxd),
        .uart_txd(uart2_txd),
        .ctrl_enabled(pc_ctrl_enabled),
        .ctrl_live(pc_ctrl_live),
        .ctrl_waveform(pc_ctrl_waveform),
        .ctrl_ramp_p(pc_ctrl_ramp_p),
        .ctrl_phase_step(pc_ctrl_phase_step),
        .ctrl_phase(pc_ctrl_phase),
        .ctrl_phase_apply(pc_ctrl_phase_apply),
        .ctrl_amplitude(pc_ctrl_amplitude),
        .ctrl_commit_toggle(pc_ctrl_commit_toggle)
    );
