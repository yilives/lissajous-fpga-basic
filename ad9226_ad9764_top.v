// 3PA1030 input tracker and AD9764 Lissajous waveform generator.
//
// The FPGA samples the input sine, measures its peak-to-peak code, detects
// positive-going centre crossings, and drives a phase-disciplined DDS.  This
// supports the four digital processing modes required by F题:
//   MODE_LINE        : Y = A * sin(wt), for the requirement-1 diagonal.
//   MODE_QUADRATURE  : Y = A * sin(wt + 90 degrees), for a circle/ellipse.
//   MODE_DOUBLE      : Y = A * sin(2wt), for the symmetric infinity figure.
// All modes share one fundamental NCO whose phase is locked by the block I/Q
// PLL (adc_block_iq_pll.v); the 90-degree shift and the 2f relationship are
// derived in the waveform phase, never inserted as a phase step in the NCO.
module ad9226_ad9764_top (
    input  wire        clk_50m,
    input  wire        gnd_guard_83,
    // S3 on the core board (IO85): toggles visual UART2 ownership.
    input  wire        vision_key_n,
    // S4 on the core board (IO87): pulled high, pressed to GND.
    input  wire        mode_key_n,

    output wire [13:0] dac_data,
    output wire        dac_clk,

    input  wire [9:0]  adc_data,
    input  wire        adc_otr,
    output wire        adc_oe,
    output wire        adc_clk,

    // 0.91" OLED SSD1306 I2C (pin 142=SCL, 144=SDA)
    inout  wire        oled_scl,
    inout  wire        oled_sda,

    // UART1: pin 141=TX, 143=RX, 115200 baud
    output wire        uart1_txd,
    input  wire        uart1_rxd,

    // UART2: pin 133=TX, 136=RX, 115200 baud
    output wire        uart2_txd,
    input  wire        uart2_rxd
);

    // One press of S4 advances to the next mode.  The default after power-up
    // is requirement 1 (diagonal); the cycle then follows the test order
    // 1 -> 2 -> 3 -> 4 (four fixed heights), wrapping back to requirement 1.
    localparam [2:0] MODE_LINE         = 3'd0; // Req. 1: Y = A*sin(wt), diagonal
    localparam [2:0] MODE_CIRCLE_MATCH = 3'd1; // Req. 2: Y = A*sin(wt+90deg)
    localparam [2:0] MODE_DOUBLE_MATCH = 3'd2; // Req. 3: Y = A*sin(2wt), equal amplitude
    // Requirement 4 extends requirement 3. These are not circle modes:
    // each one retains Y = A_set*sin(2wt), only changing the Y peak-to-peak
    // display height.
    localparam [2:0] MODE_DOUBLE_2DIV  = 3'd3; // Req. 4: Y = 2 div p-p
    localparam [2:0] MODE_DOUBLE_4DIV  = 3'd4; // Req. 4: Y = 4 div p-p
    localparam [2:0] MODE_DOUBLE_6DIV  = 3'd5; // Req. 4: Y = 6 div p-p
    localparam [2:0] MODE_DOUBLE_8DIV  = 3'd6; // Req. 4: Y = 8 div p-p

    // DAC analogue gain calibration in Q10.  Scope measurement is
    // authoritative for gain: at 2 kHz the input was 4.02 Vpp (CH3) and the
    // AD9764 output 3.94 Vpp (CH4), so the gain is raised to
    // 1244 * 4.02 / 3.94 = 1269.  Re-measure on the bench and adjust if the
    // follow modes (Req. 1/2/3) are not exactly 1:1.  The camera's
    // perspective-derived span must not overwrite this calibration.
    localparam [10:0] DAC_GAIN_Q10 = 11'd1269;
    // Standard AD9764 bipolar-code centre.
    // CH4 measured -69.6 mV at 4 Vpp. About 0.5 mV/DAC code here, so the
    // centre is shifted by +140 codes.  The trim is added AFTER the gain
    // product, so it changes the output DC level without touching the
    // peak-to-peak amplitude.  This is what keeps the figure-eight centred
    // on the scope midpoint (Req. 3/4 "not at midpoint" fix).
    localparam signed [23:0] DAC_CODE_CENTER = 24'sd8192;
    localparam signed [13:0] DAC_DC_TRIM_CODES = 14'sd140; // -69.6 mV -> +140 codes

    // Temporary controlled test: bypass every tracker/DDS decision and show
    // exactly the ADC sample captured in FPGA on the AD9764 output.
    // Normal operation: ADC is measurement-only; DAC is generated by DDS.
    localparam ADC_RAW_DIAGNOSTIC = 1'b0;
    // Controlled 100 kHz DDS test.  This bypasses only the ADC tracker and
    // phase loop; the DAC clock, output pins, code pipeline and analogue path
    // are identical to the normal design.  Set to 0 for normal operation.
    localparam DDS_FIXED_100K_DIAGNOSTIC = 1'b0;
    // DAC bus verification: toggle one FPGA data bit about midscale every
    // 100 us.  This is a hardware wiring/bit-order diagnostic, not a DDS mode.
    localparam DAC_BIT_WALK_DIAGNOSTIC = 1'b0;
    // Reference-path test: the same 128-point sine ROM used by the proven
    // zuolan design.  This bypasses the custom quarter-wave interpolator.
    localparam REFERENCE_ROM_100K_DIAGNOSTIC = 1'b0;

    // PLL-synchronous clock domains. ADC and DAC both run at 25 MHz. Data
    // changes on the DAC falling edge, leaving a full 20 ns before the next
    // AD9764 rising sampling edge.
    localparam integer PLL_INPUT_CLK_HZ = 50000000;
    localparam integer VISION_KEY_DEBOUNCE_TICKS = PLL_INPUT_CLK_HZ / 100;
    // Common 800 MHz VCO: ADC=16/32, DAC=16/8, capture=16/8.
    localparam integer PLL_MULTIPLY     = 16;
    // Proven 25 MHz ADC conversion clock; 100 MHz capture samples its settled bus.
    localparam integer ADC_CLK_DIV      = 32;
    // 50 MHz * 16 / 32 = 25 MHz: AD9764 sample clock.
    localparam integer DAC_PLL_MULTIPLY = 16;
    localparam integer DAC_CLK_DIV      = 32;
    localparam integer ADC_CLK_HZ =
        (PLL_INPUT_CLK_HZ * PLL_MULTIPLY) / ADC_CLK_DIV;
    localparam integer DAC_CLK_HZ =
        (PLL_INPUT_CLK_HZ * DAC_PLL_MULTIPLY) / DAC_CLK_DIV;
    // 10 ms mechanical-key debounce, derived from the current ADC clock.
    localparam integer KEY_DEBOUNCE_TICKS = ADC_CLK_HZ / 100;
    localparam [31:0] ADC_CLK_HZ_U = ADC_CLK_HZ;
    localparam [28:0] DAC_CLK_HZ_U = DAC_CLK_HZ[28:0];
    // This is 1 because DAC and ADC waveform clocks both run at 25 MHz.  It is derived rather
    // than hard-coded, so frequency-word conversion remains correct whenever
    // the DAC PLL ratio is changed.
    localparam [3:0] DAC_TICKS_PER_ADC_TICK_U = DAC_TICKS_PER_ADC_TICK;
    localparam integer DAC_TICKS_PER_ADC_TICK =
        (DAC_CLK_HZ >= ADC_CLK_HZ) ? (DAC_CLK_HZ / ADC_CLK_HZ) : 1;
    localparam integer ADC_TICKS_PER_DAC_TICK =
        (ADC_CLK_HZ >= DAC_CLK_HZ) ? (ADC_CLK_HZ / DAC_CLK_HZ) : 1;

    localparam [63:0] DEFAULT_PHASE_STEP_CALC = (64'd1000 << 32) / ADC_CLK_HZ;
    localparam [31:0] DEFAULT_PHASE_STEP = DEFAULT_PHASE_STEP_CALC[31:0];
    localparam [63:0] DEFAULT_DAC_PHASE_STEP_CALC = (64'd1000 << 32) / DAC_CLK_HZ;
    localparam [31:0] DEFAULT_DAC_PHASE_STEP = DEFAULT_DAC_PHASE_STEP_CALC[31:0];
    localparam [63:0] FIXED_100K_DAC_PHASE_STEP_CALC =
        (64'd100000 << 32) / DAC_CLK_HZ;
    localparam [31:0] FIXED_100K_DAC_PHASE_STEP =
        FIXED_100K_DAC_PHASE_STEP_CALC[31:0];
    localparam [9:0] FIXED_100K_PP_CODE = 10'd400;
    localparam integer BIT_WALK_HOLD_TICKS = DAC_CLK_HZ / 10000;

    localparam integer MIN_INPUT_PERIOD_SAMPLES =
        (ADC_CLK_HZ + 99999) / 100000;

    // Calibrated physical path delay = 442.8 ns, converted from real time
    // into ADC sample periods whenever ADC_CLK_DIV is changed.
    // Includes the registered DAC multiply stage (one 50 MHz clock = 20 ns).
    localparam [63:0] PATH_DELAY_PS = 64'd462800;
    localparam [63:0] INPUT_PATH_DELAY_Q8_CALC =
        (PATH_DELAY_PS * ADC_CLK_HZ * 64'd256 + 64'd500000000000) /
         64'd1000000000000;
    localparam [13:0] INPUT_PATH_DELAY_Q8 = INPUT_PATH_DELAY_Q8_CALC[13:0];
    // Same physical path delay in DAC ticks; evaluated in the 25 MHz DAC domain.
    localparam [63:0] DAC_PATH_DELAY_Q8_CALC =
        (PATH_DELAY_PS * DAC_CLK_HZ * 64'd256 + 64'd500000000000) /
         64'd1000000000000;
    localparam [13:0] DAC_PATH_DELAY_Q8 = DAC_PATH_DELAY_Q8_CALC[13:0];
    // Extra 2f output-chain delay, calibrated in time (not fixed degrees).
    // 167 ns is 12 deg at 200 kHz, but only 0.12 deg at 2 kHz.
    localparam [63:0] DOUBLE_EXTRA_DELAY_PS = 64'd167000;
    localparam [63:0] DOUBLE_EXTRA_DELAY_Q8_CALC =
        (DOUBLE_EXTRA_DELAY_PS * DAC_CLK_HZ * 64'd256 + 64'd500000000000) /
         64'd1000000000000;
    localparam [13:0] DOUBLE_EXTRA_DELAY_Q8 = DOUBLE_EXTRA_DELAY_Q8_CALC[13:0];
    localparam [63:0] DEFAULT_PATH_PHASE_PRODUCT_CALC =
        DEFAULT_PHASE_STEP * INPUT_PATH_DELAY_Q8;
    localparam [31:0] DEFAULT_PATH_PHASE_ADVANCE =
        DEFAULT_PATH_PHASE_PRODUCT_CALC[39:8];
    localparam integer AMPLITUDE_WINDOW_SAMPLES = (ADC_CLK_HZ * 2) / 1000;
    // Frequency-independent part of the Y-path phase calibration: +7.396 degrees.
    localparam [31:0] QUADRATURE_PHASE_TRIM = 32'd88237717;
    // No fixed 2f phase trim: the target must remain frequency-dependent.
    localparam [31:0] DOUBLE_PHASE_TRIM = 32'd0;
    localparam [31:0] DEFAULT_PHASE_ANCHOR =
        32'h40000000 + QUADRATURE_PHASE_TRIM + DEFAULT_PATH_PHASE_ADVANCE;
    // Zero-cross hysteresis is made adaptive to the measured ADC Vpp.  A
    // fixed 8-code threshold rejects low-level inputs (below about 160 mVpp
    // at the module input mapping) and leaves the DDS stuck at its default
    // 1 kHz.  The adaptive range is 1...8 codes.
    localparam [9:0] ZERO_HYST_MAX_CODE = 10'd8;

    wire adc_sample_clk;
    wire dac_sample_clk;
    wire adc_capture_clk;
    wire pll_locked;

    // ADC-clock-domain tracker state.
    reg [15:0] period_count;
    // Sum eight complete cycles before changing the DDS frequency word.  This
    // is the FPGA-only equivalent of the reference design's block capture:
    // acquisition stays continuous while estimation is deliberately slower.
    reg [19:0] period_sum;
    reg [4:0]  period_average_count;
    reg        divider_busy;
    reg [5:0]  divider_bit;
    reg [15:0] divider_denominator;
    reg [16:0] divider_remainder;
    reg [32:0] divider_quotient;
    // The ADC-domain reciprocal yields a phase word per ADC tick.  At a
    // DAC/ADC clock ratio before crossing to the DAC domain.  Do that as a
    // 32-cycle restoring divider rather than as one wide combinational
    // divide path in the 100 MHz capture domain.
    reg        dac_ratio_busy;
    reg [5:0]  dac_ratio_bit;
    reg [31:0] dac_ratio_dividend;
    reg [3:0]  dac_ratio_remainder;
    reg [31:0] dac_ratio_quotient;
    reg [16:0] amplitude_counter;
    reg [9:0]  amplitude_max;
    reg [9:0]  amplitude_min;
    reg [9:0]  input_pp_code;
    reg [9:0]  input_center_code;
    (* preserve *) reg [9:0] adc_sample;
    (* preserve *) reg       adc_otr_sample;

    // FPGA-only capture pipeline.  c2 is 100 MHz while the 3PA1030 clock is
    // 25 MHz: detect the ADC rising edge, wait one base-clock tick, then
    // accept the parallel bus.  This generates one valid sample per ADC
    // conversion and leaves a deterministic 35 ns physical settling interval.
    reg        adc_clk_meta_raw;
    reg        adc_clk_sync_raw;
    reg        adc_clk_sync_d_raw;
    reg        adc_capture_pending_raw;
    (* preserve *) reg        adc_sample_valid_raw;
    (* preserve *) reg [9:0]  adc_raw_sample;
    (* preserve *) reg        adc_raw_otr;
    // 50 MHz capture-domain history for single-sample impulse rejection.
    reg [9:0] adc_capture_z1;
    reg [9:0] adc_capture_z2;
    reg [9:0]  adc_previous;
    // Three delayed samples form a 4-point moving average for phase tracking.
    // Amplitude measurement remains on raw samples so its scale is unchanged.
    reg [9:0]  adc_filter_z1;
    reg [9:0]  adc_filter_z2;
    reg [9:0]  adc_filter_z3;
    reg [9:0]  adc_phase_filtered_previous;
    reg [7:0]  phase_cross_fraction_adc;
    reg        input_high;
    // Register crossing events before they reach the wide period-counter mux.
    // The one-ADC-sample delay is fixed and therefore does not bias frequency.
    reg        positive_crossing_reg;
    reg        negative_crossing_reg;
    reg        anchor_toggle_adc;
    reg [31:0] phase_step_dac_adc;
    reg [31:0] phase_anchor_adc;
    reg [31:0] input_path_phase_adc;


    // IO87/S4 button synchroniser, debounce filter and mode state.
    reg        mode_key_meta;
    reg        mode_key_sync;
    reg        mode_key_stable;
    reg [20:0] mode_key_count;
    reg [2:0]  mode_select_adc;
    // DAC-clock-domain DDS.  ADC estimates are held stable between updates
    // and transferred through two synchronizing registers.
    // Update the code bus at every 25 MHz DAC clock. At 100 kHz this retains
    // 250 samples/cycle, which is sufficient and has proved the stable board
    // operating point.
    localparam [1:0] DDS_UPDATE_DIV_MINUS1 = 2'd0;
    reg [1:0]  dac_update_count;
    wire        dac_data_update_tick = (dac_update_count == DDS_UPDATE_DIV_MINUS1);
    reg [31:0] nco_phase_dac;
    // UART2 command data crosses from the 50 MHz control clock to the DAC
    // clock through two register stages. A commit toggle marks a new command.
    reg        pc_ctrl_live_meta, pc_ctrl_live_sync;
    reg [1:0]  pc_waveform_meta, pc_waveform_sync;
    reg [7:0]  pc_ramp_p_meta, pc_ramp_p_sync;
    reg [31:0] pc_phase_step_meta, pc_phase_step_sync;
    reg [31:0] pc_phase_meta, pc_phase_sync;
    reg        pc_phase_apply_meta, pc_phase_apply_sync;
    reg [9:0]  pc_amplitude_meta, pc_amplitude_sync;
    reg        pc_commit_meta, pc_commit_sync, pc_commit_seen;
    reg        vision_key_meta, vision_key_sync, vision_key_stable;
    reg [18:0] vision_key_count;
    reg        visual_mode_enabled;
    // Pre-register the mode-selected phase increment.  This keeps the
    // button-mode mux out of the 125 MHz NCO feedback adder.
    reg [31:0] nco_step_reg;
    reg [31:0] nco_increment_reg;
    reg [31:0] requested_phase_anchor_reg;
    reg signed [31:0] phase_correction_reg;
    reg signed [31:0] phase_correction_apply_reg;
    // Accumulate eight phase-anchor errors before changing DDS phase.
    reg signed [35:0] phase_error_sum;
    reg [2:0] phase_error_count;
    // Continuous PLL term: applied at every DDS update, never as a phase step.
    reg signed [31:0] phase_rate_correction;
    reg [31:0] phase_step_dac_meta;
    reg [31:0] phase_step_dac_sync;
    reg [31:0] phase_anchor_meta;
    reg [31:0] phase_anchor_sync;
    reg [31:0] input_path_phase_meta;
    reg [31:0] input_path_phase_sync;
    reg [7:0]  phase_cross_fraction_meta;
    reg [7:0]  phase_cross_fraction_sync;
    reg [9:0]  input_pp_meta;
    reg [9:0]  input_pp_dac;
    reg [9:0]  adc_data_meta;
    reg [9:0]  adc_data_dac;
    reg        anchor_toggle_meta;
    reg        anchor_toggle_sync;
    reg        anchor_toggle_seen;
    // [AI Mod: crossing-time phase snapshot]
    reg [31:0] nco_phase_meta_adc;
    reg [31:0] nco_phase_sync_adc;
    reg [31:0] anchor_phase_snap_adc;
    reg [31:0] anchor_phase_snap_meta;
    reg [31:0] anchor_phase_snap_sync;
    // Signed crossing-phase error: the NCO phase at the crossing, measured
    // against the 0 reference, taken negative so a leading NCO (snap > 0)
    // is pulled back and a lagging NCO (snap near 2^32) is pushed forward.
    // The plain 33-bit negation handles both cases and the 0/2pi boundary
    // correctly; an unsigned subtraction here 0-extends and flips sign for
    // every lagging crossing, which made the anchor diverge.
    wire signed [32:0] anchor_snap_err = -({1'b0, anchor_phase_snap_sync});
    reg [2:0]  mode_select_meta;
    reg [2:0]  mode_select_dac;
    reg [9:0] requested_pp_code_reg;
    reg [20:0] amplitude_gain_product_reg;
    reg [9:0] output_pp_code_reg;
    reg signed [23:0] dac_product_reg;
    reg [13:0] dac_data_reg;
    // The ROM output is synchronous; retain the fractional phase for one
    // DAC cycle so it addresses the same table interval as the ROM data.
    reg [21:0] dds_rom_fraction_reg;
    reg [31:0] reference_nco_phase;
    reg [13:0] bit_walk_count;
    reg [3:0]  bit_walk_index;
    wire [9:0] zero_hyst_from_pp = input_pp_code >> 4;
    wire [9:0] zero_hyst_code = (zero_hyst_from_pp == 10'd0) ? 10'd1 :
                                (zero_hyst_from_pp > ZERO_HYST_MAX_CODE) ?
                                ZERO_HYST_MAX_CODE : zero_hyst_from_pp;
    wire [13:0] bit_walk_dac_code =
        14'h2000 ^ (14'd1 << bit_walk_index);
    wire reference_rom_clock = ~dac_sample_clk;
    wire [9:0] reference_rom_address = reference_nco_phase[31:22];
    wire [13:0] reference_rom_data;
    wire signed [14:0] reference_rom_signed =
        $signed({1'b0, reference_rom_data}) - 15'sd8191;
    wire signed [14:0] reference_rom_scaled = reference_rom_signed >>> 2;
    wire [13:0] reference_rom_dac_code =
        14'd8192 + reference_rom_scaled;
    reference_sin_rom1024 u_reference_sin_rom1024 (
        .address(reference_rom_address),
        .clock  (reference_rom_clock),
        .q      (reference_rom_data)
    );


    // DDS waveform source: 1024-point full-wave ROM, linearly interpolated
    // over the lower 22 NCO phase bits. The reference ROM retains its
    // deterministic registered output; interpolation removes the 12-sample
    // stairs visible at 2 kHz on a 25 MHz DAC clock.
    wire [9:0] dds_rom_address = dds_wave_phase_dac[31:22];
    wire [9:0] dds_rom_next_address = dds_rom_address + 10'd1;
    wire [13:0] dds_rom_data;
    wire [13:0] dds_rom_next_data;
    wire signed [14:0] dds_rom_signed =
        $signed({1'b0, dds_rom_data}) - 15'sd8191;
    wire signed [14:0] dds_rom_next_signed =
        $signed({1'b0, dds_rom_next_data}) - 15'sd8191;
    wire signed [15:0] dds_rom_delta = dds_rom_next_signed - dds_rom_signed;
    wire signed [38:0] dds_rom_interpolation_product =
        dds_rom_delta * $signed({1'b0, dds_rom_fraction_reg});
    wire signed [15:0] dds_rom_interpolated = dds_rom_signed +
        (dds_rom_interpolation_product >>> 22);
    wire signed [12:0] dds_sine_code_from_rom = dds_rom_interpolated >>> 2;
    reference_sin_rom1024 u_dds_sin_rom1024 (
        .address(dds_rom_address),
        .clock  (reference_rom_clock),
        .q      (dds_rom_data)
    );
    reference_sin_rom1024 u_dds_sin_rom1024_next (
        .address(dds_rom_next_address),
        .clock  (reference_rom_clock),
        .q      (dds_rom_next_data)
    );
    wire [10:0] high_threshold_extended = {1'b0, input_center_code} + {1'b0, zero_hyst_code};
    wire [9:0] high_threshold = high_threshold_extended[10] ? 10'd1023
                                                           : high_threshold_extended[9:0];
    wire [9:0] low_threshold = (input_center_code > zero_hyst_code)
                             ? (input_center_code - zero_hyst_code) : 10'd0;

    // Schmitt crossing state: each half-cycle can create exactly one event.
    // c2 is phase-shifted from the ADC launch clock; every c2 edge therefore
    // captures one deliberately delayed and valid ADC conversion result.
    wire [9:0] captured_adc_data = adc_raw_sample;
    wire        captured_adc_otr = adc_raw_otr;
    wire [11:0] adc_phase_filter_sum = {2'b00, captured_adc_data} +
                                       {2'b00, adc_filter_z1} +
                                       {2'b00, adc_filter_z2} +
                                       {2'b00, adc_filter_z3};
    wire [9:0] adc_phase_filtered_data = adc_phase_filter_sum[11:2];
    wire positive_crossing = !input_high && (adc_phase_filtered_data >= high_threshold);
    wire negative_crossing =  input_high && (adc_phase_filtered_data <= low_threshold);

    // Keep the Schmitt state for noise immunity, but locate the threshold
    // crossing to 1/16 of an ADC period for the phase loop.
    wire phase_positive_crossing = !input_high &&
        (adc_phase_filtered_previous < high_threshold) &&
        (adc_phase_filtered_data >= high_threshold);
    // Phase uses the actual filtered centre crossing.  The high/low Schmitt
    // thresholds remain exclusively for robust period counting.
    wire phase_zero_crossing = !input_high &&
        (adc_phase_filtered_previous < input_center_code) &&
        (adc_phase_filtered_data >= input_center_code);
    wire [10:0] phase_cross_numerator =
        {1'b0, high_threshold} - {1'b0, adc_phase_filtered_previous};
    wire [10:0] phase_cross_denominator =
        {1'b0, adc_phase_filtered_data} - {1'b0, adc_phase_filtered_previous};
    function [7:0] crossing_fraction_q8;
        input [10:0] numerator;
        input [10:0] denominator;
        integer level;
        reg [14:0] scaled_numerator;
        begin
            if (denominator == 11'd0) crossing_fraction_q8 = 8'd128;
            else if (numerator >= denominator) crossing_fraction_q8 = 8'd255;
            else begin
                scaled_numerator = {numerator, 4'b0000};
                crossing_fraction_q8 = 8'd0;
                for (level = 1; level < 16; level = level + 1)
                    if (scaled_numerator >= denominator * level)
                        crossing_fraction_q8 = level * 16;
            end
        end
    endfunction
    wire [7:0] phase_cross_fraction_next =
        crossing_fraction_q8(phase_cross_numerator, phase_cross_denominator);
    wire [9:0] amplitude_max_next = (captured_adc_data > amplitude_max) ? captured_adc_data : amplitude_max;
    wire [9:0] amplitude_min_next = (captured_adc_data < amplitude_min) ? captured_adc_data : amplitude_min;
    wire [9:0] amplitude_pp_next  = amplitude_max_next - amplitude_min_next;
    wire [10:0] amplitude_sum_next = {1'b0, amplitude_max_next} + {1'b0, amplitude_min_next};


    wire [17:0] divider_shifted = {divider_remainder[15:0], (divider_bit == 6'd32)};
    wire divider_ge = (divider_shifted >= {2'b00, divider_denominator});
    wire [17:0] divider_subtracted = divider_shifted - {2'b00, divider_denominator};
    wire [16:0] divider_remainder_next = divider_ge
        ? divider_subtracted[16:0] : divider_shifted[16:0];
    wire [32:0] divider_quotient_next = divider_ge
        ? (divider_quotient | (33'd1 << divider_bit)) : divider_quotient;
    wire [19:0] period_sum_next = period_sum + {4'b0000, period_count};
    wire [15:0] averaged_period = {1'b0, period_sum_next[19:5]};
    wire [4:0] dac_ratio_shifted =
        {dac_ratio_remainder, dac_ratio_dividend[dac_ratio_bit]};
    wire dac_ratio_ge =
        (dac_ratio_shifted >= {1'b0, DAC_TICKS_PER_ADC_TICK_U});
